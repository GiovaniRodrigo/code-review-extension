import { ReviewSession } from '@code-review/domain';
import { CodeReviewRepositoryPort } from '../../../ports/review/CodeReviewRepositoryPort';
import { RiskScorer } from '../../../RiskScorer';

export interface QualityReportResult {
    projectId: string;
    generatedAt: Date;
    overallScore: number;
    filesAnalyzed: number;
    criticalFindings: number;
    markdown: string;
}

export class GenerateQualityReportUseCase {
  constructor(
    private readonly repository: CodeReviewRepositoryPort,
    private readonly riskScorer = new RiskScorer()
  ) {}

  async execute(branch: string): Promise<QualityReportResult> {
    const session = await this.repository.getSessionByBranch(branch);
    if (!session) {
      throw new Error(`No review session found for branch ${branch}.`);
    }

    const findings = session.findings;
    const criticalCount = findings.filter(f => f.severity === 'error' || (f.severity as string) === 'critical').length;
    const warningCount = findings.filter(f => f.severity === 'warning').length;
    const score = this.calculateHealthScore(session);
    const reportMd = this.generateMarkdown(session, score, criticalCount, warningCount);

    return {
      projectId: branch,
      generatedAt: new Date(),
      overallScore: score,
      filesAnalyzed: new Set(findings.map(f => f.file)).size,
      criticalFindings: criticalCount,
      markdown: reportMd
    };
  }

  private calculateHealthScore(session: ReviewSession): number {
    const findings = session.findings;
    const penalty = findings.reduce((sum, finding) => {
      const severity = String(finding.severity);
      if (severity === 'critical') return sum + 20;
      if (severity === 'error') return sum + 15;
      if (severity === 'warning') return sum + 6;
      return sum + 2;
    }, 0);
    const approvedBonus = Math.min(10, findings.filter(f => f.status === 'approved').length);
    return Math.max(0, Math.min(100, 95 - penalty + approvedBonus));
  }

  private generateMarkdown(session: ReviewSession, score: number, critical: number, warnings: number): string {
    const findings = session.findings;
    const date = new Date().toISOString();
    const scoreLabel = score >= 90 ? 'Excellent' : score >= 75 ? 'Good' : score >= 60 ? 'Attention' : score >= 40 ? 'Risk' : 'Blocked';
    const files = new Set(findings.map(f => f.file));
    const approved = findings.filter(f => f.status === 'approved').length;
    const pending = findings.filter(f => f.status === 'pending').length;
    const categories = this.countBy(findings.map(f => String((f as any).category || 'code_smell')));
    const severities = this.countBy(findings.map(f => String(f.severity || 'info')));

    let md = `# Technical Quality Report\n\n`;
    md += `Generated by **Git Code Review Pro Foundation**.\n\n`;
    md += `| Field | Value |\n|---|---|\n`;
    md += `| Branch | ${escapeCell(session.branch)} |\n`;
    md += `| Generated At | ${escapeCell(date)} |\n`;
    md += `| Quality Score | ${score}/100 — ${scoreLabel} |\n`;
    md += `| Files Impacted | ${files.size} |\n`;
    md += `| Findings | ${findings.length} |\n`;
    md += `| Approved | ${approved} |\n`;
    md += `| Pending | ${pending} |\n\n`;

    md += `## Executive Summary\n\n`;
    md += `- **Decision signal:** ${this.decisionSignal(score, critical, pending)}\n`;
    md += `- **Critical/Error findings:** ${critical}\n`;
    md += `- **Warning findings:** ${warnings}\n`;
    md += `- **Human review status:** ${pending === 0 ? 'All findings have reviewer decisions.' : `${pending} finding(s) still need reviewer decision.`}\n\n`;

    md += `## Quality Distribution\n\n`;
    md += `### By Severity\n\n${this.renderCountTable(severities)}\n\n`;
    md += `### By Category\n\n${this.renderCountTable(categories)}\n\n`;

    md += `## Top Findings\n\n`;
    md += `| File | Line | Severity | Status | Message |\n`;
    md += `| :--- | ---: | :--- | :--- | :--- |\n`;
    [...findings]
      .sort((a, b) => this.severityRank(b.severity) - this.severityRank(a.severity))
      .slice(0, 30)
      .forEach(f => {
        md += `| \`${escapeCell(f.file)}\` | ${f.line || 1} | **${escapeCell(String(f.severity)).toUpperCase()}** | \`${escapeCell(String(f.status))}\` | ${escapeCell(f.message)} |\n`;
      });
    if (!findings.length) md += `| - | - | - | - | No findings recorded. |\n`;

    md += `\n## Recommendations\n\n`;
    md += this.recommendations(score, critical, warnings, pending).map(item => `- ${item}`).join('\n');
    md += `\n\n## Human-in-the-Loop Declaration\n\n`;
    md += `AI suggestions are advisory. The final approval decision belongs to the code reviewer.\n`;
    return md;
  }

  private countBy(values: string[]): Record<string, number> {
    return values.reduce<Record<string, number>>((acc, value) => {
      acc[value] = (acc[value] || 0) + 1;
      return acc;
    }, {});
  }

  private renderCountTable(counts: Record<string, number>): string {
    const rows = Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([key, value]) => `| ${escapeCell(key)} | ${value} |`).join('\n');
    return `| Item | Count |\n|---|---:|\n${rows || '| - | 0 |'}`;
  }

  private decisionSignal(score: number, critical: number, pending: number): string {
    if (critical > 0) return 'Do not approve before critical/error findings are reviewed.';
    if (score < 60) return 'High-risk change. Review carefully before approval.';
    if (pending > 0) return 'Review can continue, but pending findings require human decision.';
    return 'Review appears ready for final human approval.';
  }

  private recommendations(score: number, critical: number, warnings: number, pending: number): string[] {
    const items: string[] = [];
    if (critical > 0) items.push('Resolve or explicitly accept critical/error findings before approval.');
    if (warnings > 0) items.push('Review warning findings and decide whether they should block the PR.');
    if (pending > 0) items.push('Use the HITL workflow to approve, reject or comment on pending findings.');
    if (score < 75) items.push('Run revalidation after fixes to verify score improvement.');
    if (!items.length) items.push('Maintain reviewer approval evidence by exporting the Markdown or PDF report.');
    return items;
  }

  private severityRank(s: string): number {
      if (s === 'critical') return 4;
      if (s === 'error') return 3;
      if (s === 'warning') return 2;
      return 1;
  }
}

function escapeCell(value: unknown): string {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}
