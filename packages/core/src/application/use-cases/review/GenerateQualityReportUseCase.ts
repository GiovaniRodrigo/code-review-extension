import { ReviewSession } from '@code-review/domain';
import { CodeReviewRepositoryPort } from '../../../ports/review/CodeReviewRepositoryPort';
import { FileRiskScore, RiskScorer } from '../../../RiskScorer';

export interface QualityReportResult {
    projectId: string;
    generatedAt: Date;
    overallScore: number;
    filesAnalyzed: number;
    criticalFindings: number;
    markdown: string;
}

export class GenerateQualityReportUseCase {
  constructor(
    private readonly repository: CodeReviewRepositoryPort,
    private readonly riskScorer = new RiskScorer()
  ) {}

  async execute(branch: string): Promise<QualityReportResult> {
    const session = await this.repository.getSessionByBranch(branch);
    if (!session) {
      throw new Error(`No review session found for branch ${branch}.`);
    }

    const findings = session.findings;
    const criticalCount = findings.filter(f => f.severity === 'error' || (f.severity as string) === 'critical').length;
    const warningCount = findings.filter(f => f.severity === 'warning').length;

    // Calculate a simple aggregate health score (0-100)
    // 100 is perfect, penalties for findings
    let healthScore = 100 - (criticalCount * 15) - (warningCount * 5);
    healthScore = Math.max(0, healthScore);

    const reportMd = this._generateMarkdown(session, healthScore, criticalCount, warningCount);

    return {
      projectId: branch,
      generatedAt: new Date(),
      overallScore: healthScore,
      filesAnalyzed: new Set(findings.map(f => f.file)).size,
      criticalFindings: criticalCount,
      markdown: reportMd
    };
  }

  private _generateMarkdown(session: ReviewSession, score: number, critical: number, warnings: number): string {
    const date = new Date().toLocaleDateString();
    const scoreEmoji = score > 80 ? '🟢' : score > 50 ? '🟡' : '🔴';

    let md = `# Technical Quality Report — Branch: ${session.branch}\n\n`;
    md += `**Date:** ${date}\n`;
    md += `**Overall Health Score:** ${scoreEmoji} ${score}/100\n\n`;
    
    md += `## Executive Summary\n`;
    md += `- **Critical Issues:** ${critical}\n`;
    md += `- **Warnings:** ${warnings}\n`;
    md += `- **Files Impacted:** ${new Set(session.findings.map(f => f.file)).size}\n\n`;

    md += `## 🚩 Top Findings\n\n`;
    
    const sortedFindings = [...session.findings]
        .sort((a, b) => this._severityRank(b.severity) - this._severityRank(a.severity))
        .slice(0, 20);

    md += `| File | Severity | Message | Status |\n`;
    md += `| :--- | :--- | :--- | :--- |\n`;
    
    sortedFindings.forEach(f => {
        const file = f.file.split('/').pop();
        md += `| \`${file}\` | **${f.severity.toUpperCase()}** | ${f.message} | \`${f.status}\` |\n`;
    });

    md += `\n---\n*Report generated by AI Code Review Extension*`;
    return md;
  }

  private _severityRank(s: string): number {
      if (s === 'critical' || s === 'error') return 3;
      if (s === 'warning') return 2;
      return 1;
  }
}
